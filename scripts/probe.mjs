import { readFile } from "node:fs/promises";
import { fetchPlan, spread, MODELS } from "../snow.js";
const { cams } = JSON.parse(await readFile("cams.json", "utf8"));
const ids = JSON.parse(await readFile("watchlist.json", "utf8"));
const list = ids.map(i => cams.find(c => c.id === i)).filter(Boolean);
const plans = await fetchPlan(list, 7);
const days = plans[0].days;
console.log("days", days.join(" "));
const rows = list.map((c, i) => { const p = plans[i]; const tot = p.snow.reduce((s, v) => s + (v || 0), 0);
  const lo = days.reduce((s, _, k) => s + (spread(p, "snow", k)?.min || 0), 0), hi = days.reduce((s, _, k) => s + (spread(p, "snow", k)?.max || 0), 0);
  return { n: c.name, e: c.elev, tot, lo, hi, d: p.snow.map(v => Math.round(v || 0)), sun: p.sun.map(v => Math.round(v || 0)) }; });
rows.sort((a, b) => b.tot - a.tot);
for (const r of rows) console.log(`${r.n.padEnd(24)} ${String(r.e).padStart(4)}  ${Math.round(r.tot).toString().padStart(3)} cm (${Math.round(r.lo)}–${Math.round(r.hi)})  ${r.d.join(" ")}  | sun ${r.sun.join(" ")}`);
